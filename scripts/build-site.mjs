// Assembles the public website into site-dist/ for GitHub Pages.
//
//   site/                     page source, copied as is (HTML gets its includes resolved)
//   src/lib/tokens/generated  token CSS from `npm run tokens` (run that first)
//   tokens/primitive          palette primitives, emitted as --palette-* for illustrations
//   brand/                    favicons, social card; logo and motif SVGs inlined via includes
//   @fontsource-variable      Literata and Inter, Latin subset, self-hosted
//
// HTML includes: `<!-- include:brand/motif/gossamer-dew.svg -->` is replaced by the file's
// markup. `<!-- include:brand/logo/feedrico-lockup-horizontal.svg logo -->` also swaps the
// default logo colours for CSS variables, so one inlined logo follows the theme the way the
// default and -reversed files do.
//
// The site adds a few text/background pairs of its own (the clock phases); they are checked
// against WCAG 2.2 AA here, and the build fails if one misses.

import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { contrastRatio } from './contrast.mjs';

const OUT = 'site-dist';
const TOKENS = 'src/lib/tokens/generated';
const FONTS = 'node_modules/@fontsource-variable';

if (!existsSync(join(TOKENS, 'theme-light.css'))) {
  console.error('Token CSS missing: run `npm run tokens` first (npm run site:build does).');
  process.exit(1);
}

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

// --- Page source -------------------------------------------------------------------------------

await cp('site', OUT, { recursive: true });

const LOGO_COLOURS = {
  '#2B2541': 'var(--logo-ink)',
  '#E89C26': 'var(--logo-drop)',
  '#CF8015': 'var(--logo-strand)',
};

async function inline(path, mode) {
  let svg = await readFile(path, 'utf8');
  svg = svg
    .replace(/<\?xml[^>]*\?>\s*/g, '')
    .replace(/<!--[\s\S]*?-->\s*/g, '')
    .trim();
  if (mode === 'logo') {
    for (const [hex, value] of Object.entries(LOGO_COLOURS)) {
      svg = svg.replaceAll(`fill="${hex}"`, `style="fill:${value}"`);
    }
    if (/fill="#/.test(svg)) throw new Error(`${path}: unmapped logo colour`);
    // The surrounding link names the logo; the SVG itself is decoration there.
    svg = svg
      .replace(/<title>[^<]*<\/title>\s*/, '')
      .replace(/ role="img" aria-label="[^"]*"/, ' aria-hidden="true" focusable="false"');
  }
  return svg;
}

for (const file of await readdir(OUT)) {
  if (!file.endsWith('.html')) continue;
  const target = join(OUT, file);
  let html = await readFile(target, 'utf8');
  const includes = [...html.matchAll(/<!--\s*include:(\S+)(?:\s+(\w+))?\s*-->/g)];
  for (const [marker, path, mode] of includes) {
    html = html.replace(marker, await inline(path, mode));
  }
  await writeFile(target, html);
}

// --- Tokens ------------------------------------------------------------------------------------

await mkdir(join(OUT, 'css/tokens'), { recursive: true });
for (const file of ['base.css', 'theme-light.css', 'theme-dark.css']) {
  await cp(join(TOKENS, file), join(OUT, 'css/tokens', file));
}

// Primitives are not part of the app's CSS (UI code uses semantic tokens only). The site's
// illustrations and clock phases need a few raw palette colours, so emit them under a name that
// makes clear they are primitives.
const { palette } = JSON.parse(await readFile('tokens/primitive/color.json', 'utf8'));
const primitives = {};
for (const [ramp, steps] of Object.entries(palette)) {
  if (ramp.startsWith('$')) continue;
  for (const [step, token] of Object.entries(steps)) {
    if (!step.startsWith('$')) primitives[`${ramp}-${step}`] = token.$value;
  }
}
await writeFile(
  join(OUT, 'css/tokens/palette.css'),
  '/* Generated by scripts/build-site.mjs from tokens/primitive/color.json. */\n:root {\n' +
    Object.entries(primitives)
      .map(([name, value]) => `  --palette-${name}: ${value};`)
      .join('\n') +
    '\n}\n',
);

// --- Contrast of the site's own pairs ----------------------------------------------------------

function themeColours(css) {
  const block = css.slice(css.indexOf('{'), css.indexOf('}'));
  return Object.fromEntries(
    [...block.matchAll(/--([\w-]+):\s*(#[0-9a-f]{3,8})\s*;/gi)].map(([, k, v]) => [k, v]),
  );
}
const light = themeColours(await readFile(join(TOKENS, 'theme-light.css'), 'utf8'));
const dark = themeColours(await readFile(join(TOKENS, 'theme-dark.css'), 'utf8'));

// Keep in sync with the [data-phase] rules in site/css/site.css.
const phases = [
  { name: 'morning', theme: light, base: primitives['paper-0'] },
  { name: 'golden hour', theme: light, base: primitives['amber-50'] },
  { name: 'night', theme: dark, base: primitives['dusk-950'], sunken: primitives['dusk-900'] },
];
const failures = [];
for (const { name, theme, base, sunken } of phases) {
  const pairs = [
    ['color-text-default', base, 4.5],
    ['color-text-muted', base, 4.5],
    ['color-text-accent', base, 4.5],
    ['color-border-focus', base, 3],
  ];
  if (sunken) pairs.push(['color-text-default', sunken, 4.5], ['color-text-muted', sunken, 4.5]);
  for (const [fg, bg, min] of pairs) {
    const ratio = contrastRatio(theme[fg], bg);
    if (ratio < min) failures.push(`${name}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, needs ${min}:1`);
  }
}
if (failures.length) {
  console.error(`\nSite contrast check failed:\n  ${failures.join('\n  ')}\n`);
  process.exit(1);
}

// --- Fonts -------------------------------------------------------------------------------------

await mkdir(join(OUT, 'fonts'), { recursive: true });
const fonts = [
  ['literata', 'literata-latin-opsz-normal.woff2'],
  ['literata', 'literata-latin-opsz-italic.woff2'],
  ['inter', 'inter-latin-wght-normal.woff2'],
];
for (const [family, file] of fonts) {
  await cp(join(FONTS, family, 'files', file), join(OUT, 'fonts', file));
}
for (const family of ['literata', 'inter']) {
  await cp(join(FONTS, family, 'LICENSE'), join(OUT, 'fonts', `LICENSE-${family}.txt`));
}

// --- Brand files served as files ---------------------------------------------------------------

for (const file of await readdir('brand/favicon')) {
  await cp(join('brand/favicon', file), join(OUT, file));
}
await cp('brand/social/og-card.png', join(OUT, 'og-card.png'));

// GitHub Pages: serve files as they are, no Jekyll (only matters for branch-based Pages; the
// Actions deployment never runs Jekyll).
await writeFile(join(OUT, '.nojekyll'), '');

console.log(`Site built into ${OUT}/; clock-phase contrast pairs pass WCAG 2.2 AA.`);
